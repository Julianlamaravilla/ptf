function setLanguage(lang) {
    localStorage.setItem('portfolio-language', lang);
    updatePageLanguage(lang);
}

function getLanguage() {
    return localStorage.getItem('portfolio-language') || 'en';
}

function updatePageLanguage(lang) {
    const t = translations[lang];
    const $ = (sel) => document.querySelector(sel);

    // Navigation
    ['about', 'skills', 'experience', 'projects', 'education', 'contact'].forEach((id, i) => {
        $(`nav a[href="#${id}"]`).textContent = t.nav[i];
    });
    const langBtn = document.getElementById('languageBtn');
    if (langBtn) langBtn.textContent = t.lang_btn;

    // CV download links (nav + hero) follow the language
    const cvFile = lang === 'es' ? 'Julian_Restrepo_CV_ES.pdf' : 'Julian_Restrepo_CV_EN.pdf';
    ['btnDownloadCv', 'btnDownloadCvNav'].forEach((id) => {
        const link = document.getElementById(id);
        if (!link) return;
        link.href = `./files/${cvFile}`;
        link.setAttribute('download', cvFile);
    });

    // Hero
    $('.hero-badge').textContent = t.hero_badge;
    $('.hero-content h1').textContent = t.hero_title;
    $('.hero-content > p').textContent = t.hero_desc;
    $('#btnViewProjects').textContent = t.cta_projects;
    $('#btnContact').textContent = t.cta_contact;
    $('#btnDownloadCv span').textContent = t.cta_download;
    $('#btnDownloadCvNav').setAttribute('aria-label', t.cta_download);
    const availBadge = $('.hero-availability');
    if (availBadge) availBadge.textContent = t.avail;

    // Section headers: about, skills, experience, projects, education
    const headers = document.querySelectorAll('.section-header');
    [
        [t.about_title, t.about_sub],
        [t.skills_title, t.skills_sub],
        [t.exp_title, t.exp_sub],
        [t.proj_title, t.proj_sub],
        [t.edu_title, t.edu_sub],
    ].forEach(([title, sub], i) => {
        headers[i].querySelector('h2').textContent = title;
        headers[i].querySelector('p').textContent = sub;
    });

    // About
    const aboutParagraphs = document.querySelectorAll('.about-content p');
    t.about.forEach((text, i) => { if (aboutParagraphs[i]) aboutParagraphs[i].innerHTML = text; });

    // Skills
    document.querySelectorAll('.skills-section .skill-category h3').forEach((h, i) => {
        if (t.skill_heads[i]) h.textContent = t.skill_heads[i];
    });
    const methodologiesH3 = $('.methodologies h3');
    if (methodologiesH3) methodologiesH3.textContent = t.methods_head;

    // Experience
    document.querySelectorAll('.experience-card').forEach((card, i) => {
        const copy = t.exp[i];
        if (!copy) return;
        card.querySelector('.experience-meta').textContent = copy.meta;
        card.querySelector('h3').textContent = copy.job;
        const bullets = card.querySelectorAll('p');
        copy.b.forEach((bullet, j) => { if (bullets[j]) bullets[j].innerHTML = bullet; });
    });

    // Projects
    document.querySelectorAll('.project-card').forEach((card) => {
        const copy = t.proj[card.dataset.project];
        if (!copy) return;
        card.querySelector('h3').textContent = copy.title;
        const description = card.querySelector('.project-content > p');
        if (description) description.innerHTML = copy.desc;
        const note = card.querySelector('.project-note');
        if (note && copy.note) note.textContent = copy.note;
        const badge = card.querySelector('.project-badge');
        if (badge && copy.badge) badge.textContent = copy.badge;
    });

    // Education & Certifications
    const eduSection = $('.education-section');
    if (eduSection) {
        const eduHeadings = eduSection.querySelectorAll('.skill-category h3');
        [t.edu_h, t.cert_h, t.lang_h].forEach((text, i) => { if (eduHeadings[i]) eduHeadings[i].textContent = text; });
        const eduLists = eduSection.querySelectorAll('.skill-list');
        [t.edu_list, t.cert_list, t.lang_list].forEach((html, i) => { if (eduLists[i]) eduLists[i].innerHTML = html; });
    }

    // Contact
    $('.contact-banner h2').textContent = t.contact_title;
    const contactSubtitle = $('.contact-subtitle');
    if (contactSubtitle) contactSubtitle.textContent = t.contact_sub;
    const contactBtns = document.querySelectorAll('.contact-cta .btn');
    if (contactBtns[0]) contactBtns[0].textContent = t.contact_email;
    if (contactBtns[1]) contactBtns[1].textContent = t.contact_li;

    // Footer
    $('.footer p').textContent = t.footer;

    document.documentElement.lang = lang;
}
