function setLanguage(lang) {
    localStorage.setItem('portfolio-language', lang);
    updatePageLanguage(lang);
}

function getLanguage() {
    return localStorage.getItem('portfolio-language') || 'en';
}

function updatePageLanguage(lang) {
    const t = translations[lang];

    // Navigation
    document.querySelector('nav a[href="#about"]').textContent = t.nav_about;
    document.querySelector('nav a[href="#skills"]').textContent = t.nav_skills;
    document.querySelector('nav a[href="#experience"]').textContent = t.nav_experience;
    document.querySelector('nav a[href="#projects"]').textContent = t.nav_projects;
    document.querySelector('nav a[href="#education"]').textContent = t.nav_education;
    document.querySelector('nav a[href="#contact"]').textContent = t.nav_contact;

    const langBtn = document.getElementById('languageBtn');
    if (langBtn) langBtn.textContent = t.nav_language;

    // Hero Section
    document.querySelector('.hero-badge').textContent = t.hero_badge;
    document.querySelector('.hero-content h1').textContent = t.hero_title;
    document.querySelector('.hero-content > p').textContent = t.hero_description;
    document.getElementById('btnViewProjects').textContent = t.hero_cta_projects;
    document.getElementById('btnContact').textContent = t.hero_cta_contact;
    document.getElementById('btnDownloadCv').textContent = t.hero_cta_download;

    const availBadge = document.querySelector('.hero-availability');
    if (availBadge) availBadge.textContent = t.hero_availability;

    // About Section
    const aboutHeaders = document.querySelectorAll('.section-header');
    aboutHeaders[0].querySelector('h2').textContent = t.about_title;
    aboutHeaders[0].querySelector('p').textContent = t.about_subtitle;

    document.querySelector('.about-content h3').textContent = t.about_name;
    const aboutParagraphs = document.querySelectorAll('.about-content p');
    aboutParagraphs[0].innerHTML = t.about_intro;
    aboutParagraphs[1].innerHTML = t.about_problem1;
    aboutParagraphs[2].innerHTML = t.about_problem2;
    aboutParagraphs[3].innerHTML = t.about_problem3;
    aboutParagraphs[4].innerHTML = t.about_fullstack;

    // Skills Section
    aboutHeaders[1].querySelector('h2').textContent = t.skills_title;
    aboutHeaders[1].querySelector('p').textContent = t.skills_subtitle;

    const skillCategories = document.querySelectorAll('.skills-section .skill-category h3');
    skillCategories[0].textContent = t.skills_primary;
    skillCategories[1].textContent = t.skills_secondary;
    skillCategories[2].textContent = t.skills_cloud;
    skillCategories[3].textContent = t.skills_ai;
    skillCategories[4].textContent = t.skills_domain;

    const methodologiesH3 = document.querySelector('.methodologies h3');
    if (methodologiesH3) methodologiesH3.textContent = t.skills_methodologies;

    // Experience Section
    aboutHeaders[2].querySelector('h2').textContent = t.experience_title;
    aboutHeaders[2].querySelector('p').textContent = t.experience_subtitle;

    const experienceCopy = {
        scala: {
            role: t.experience_scala_role,
            job: t.experience_scala_job,
            bullets: [t.experience_scala_r1, t.experience_scala_r2, t.experience_scala_r3]
        },
        kidar: {
            role: t.experience_kidar_role,
            job: t.experience_kidar_job,
            bullets: [t.experience_kidar_r1, t.experience_kidar_r2, t.experience_kidar_r3, t.experience_kidar_r4]
        }
    };

    document.querySelectorAll('.experience-card').forEach((card) => {
        const copy = experienceCopy[card.dataset.role];
        if (!copy) return;
        card.querySelector('.experience-meta').textContent = copy.role;
        card.querySelector('h3').textContent = copy.job;
        const bullets = card.querySelectorAll('p');
        copy.bullets.forEach((bullet, i) => {
            if (bullets[i]) bullets[i].innerHTML = bullet;
        });
    });

    // Projects Section
    aboutHeaders[3].querySelector('h2').textContent = t.projects_title;
    aboutHeaders[3].querySelector('p').textContent = t.projects_subtitle;

    const projectCopy = {
        adkio:   { title: t.projects_adkio_title,   desc: t.projects_adkio_desc },
        erp:     { title: t.projects_erp_title,     desc: t.projects_erp_desc,   note: t.projects_erp_note },
        jojun:   { title: t.projects_jojun_title,   desc: t.projects_jojun_desc },
        argenta: { title: t.projects_argenta_title, desc: t.projects_argenta_desc },
    };

    document.querySelectorAll('.project-card').forEach((card) => {
        const copy = projectCopy[card.dataset.project];
        if (!copy) return;
        card.querySelector('h3').textContent = copy.title;
        const description = card.querySelector('.project-content > p');
        if (description) description.innerHTML = copy.desc;
        if (copy.note) {
            const note = card.querySelector('.project-note');
            if (note) note.textContent = copy.note;
        }
    });

    // Education & Certifications Section
    aboutHeaders[4].querySelector('h2').textContent = t.education_title;
    aboutHeaders[4].querySelector('p').textContent = t.education_subtitle;

    const eduSection = document.querySelector('.education-section');
    if (eduSection) {
        const eduHeadings = eduSection.querySelectorAll('.skill-category h3');
        if (eduHeadings[0]) eduHeadings[0].textContent = t.education_heading;
        if (eduHeadings[1]) eduHeadings[1].textContent = t.certifications_heading;
        if (eduHeadings[2]) eduHeadings[2].textContent = t.languages_heading;

        const eduLists = eduSection.querySelectorAll('.skill-list');
        if (eduLists[0]) eduLists[0].innerHTML = t.education_edu_list;
        if (eduLists[1]) eduLists[1].innerHTML = t.education_cert_list;
        if (eduLists[2]) eduLists[2].innerHTML = t.education_lang_list;
    }

    // Contact Section
    document.querySelector('.contact-banner h2').textContent = t.contact_title;
    const contactSubtitle = document.querySelector('.contact-subtitle');
    if (contactSubtitle) contactSubtitle.textContent = t.contact_subtitle;
    const contactBtns = document.querySelectorAll('.contact-cta .btn');
    if (contactBtns[0]) contactBtns[0].textContent = t.contact_cta_email;
    if (contactBtns[1]) contactBtns[1].textContent = t.contact_cta_linkedin;

    // Footer
    document.querySelector('.footer p').textContent = t.footer_text;

    // Update HTML lang attribute
    document.documentElement.lang = lang;
}
